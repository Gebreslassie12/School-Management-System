(() => {
  const languageSelect = document.getElementById("languageSelect");
  if (!languageSelect) return;

  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();

  let currentLanguage = localStorage.getItem("schoolLanguage") || "en";

  function translateTextNode(node) {
    const parent = node.parentElement;
    if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) return;

    if (!originalText.has(node)) {
      originalText.set(node, node.nodeValue);
    }

    const original = originalText.get(node);
    const trimmed = original.trim();
    if (!trimmed) return;

    const translated = currentLanguage === "ti"
      ? translations[trimmed]
      : trimmed;

    if (translated !== undefined) {
      const start = original.match(/^\s*/)[0];
      const end = original.match(/\s*$/)[0];
      const nextValue = start + translated + end;

      if (node.nodeValue !== nextValue) {
        node.nodeValue = nextValue;
      }
    }
  }

  function translateElement(element) {
    if (element.nodeType === Node.TEXT_NODE) {
      translateTextNode(element);
      return;
    }

    if (element.nodeType !== Node.ELEMENT_NODE) return;

    ["placeholder", "title"].forEach(attribute => {
      if (element.hasAttribute(attribute)) {
        if (!originalAttributes.has(element)) {
          originalAttributes.set(element, {});
        }

        const saved = originalAttributes.get(element);
        if (saved[attribute] === undefined) {
          saved[attribute] = element.getAttribute(attribute);
        }

        const original = saved[attribute];
        const translated = currentLanguage === "ti"
          ? translations[original]
          : original;

        if (translated !== undefined &&
            element.getAttribute(attribute) !== translated) {
          element.setAttribute(attribute, translated);
        }
      }
    });

    Array.from(element.childNodes).forEach(translateElement);
  }

  function applyLanguage() {
    document.documentElement.lang = currentLanguage === "ti" ? "ti" : "en";
    languageSelect.value = currentLanguage;

    translateElement(document.body);
  }

  languageSelect.addEventListener("change", () => {
    currentLanguage = languageSelect.value;
    localStorage.setItem("schoolLanguage", currentLanguage);
    applyLanguage();
  });

  const observer = new MutationObserver(mutations => {
    mutations.forEach(mutation => {
      mutation.addedNodes.forEach(translateElement);

      if (mutation.type === "characterData") {
        translateTextNode(mutation.target);
      }

      if (mutation.type === "attributes") {
        translateElement(mutation.target);
      }
    });
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title"]
  });

  applyLanguage();
})();
